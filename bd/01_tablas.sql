CREATE TABLE IF NOT EXISTS usuarios (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  correo VARCHAR(150) NOT NULL UNIQUE,
  clave_hash TEXT NOT NULL,
  rol VARCHAR(20) NOT NULL CHECK (rol IN ('ADMINISTRADOR', 'CAJERO')),
  activo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS categorias (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL CHECK (length(trim(nombre)) >= 2),
  activa BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX IF NOT EXISTS categoria_nombre_unico ON categorias(lower(nombre));
CREATE TABLE IF NOT EXISTS productos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  categoria_id INTEGER NOT NULL REFERENCES categorias(id),
  nombre VARCHAR(100) NOT NULL CHECK (length(trim(nombre)) >= 2),
  descripcion VARCHAR(200) NOT NULL DEFAULT '',
  precio_centimos INTEGER NOT NULL CHECK (precio_centimos BETWEEN 1 AND 1000000),
  disponible BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS ventas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  solicitud_id UUID NOT NULL UNIQUE,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
  fecha_hora TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  metodo_pago VARCHAR(20) NOT NULL CHECK (metodo_pago IN ('EFECTIVO','TARJETA','YAPE','PLIN')),
  total_centimos INTEGER NOT NULL CHECK (total_centimos > 0)
);
CREATE TABLE IF NOT EXISTS detalle_venta (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venta_id INTEGER NOT NULL REFERENCES ventas(id),
  producto_id INTEGER NOT NULL REFERENCES productos(id),
  nombre_producto VARCHAR(100) NOT NULL,
  cantidad INTEGER NOT NULL CHECK (cantidad BETWEEN 1 AND 99),
  precio_centimos INTEGER NOT NULL CHECK (precio_centimos > 0),
  subtotal_centimos INTEGER NOT NULL CHECK (subtotal_centimos = cantidad * precio_centimos)
);
CREATE INDEX IF NOT EXISTS ventas_fecha ON ventas(fecha_hora);
CREATE INDEX IF NOT EXISTS detalle_por_venta ON detalle_venta(venta_id);

CREATE TABLE IF NOT EXISTS cajas (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
 abierta_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 cerrada_en TIMESTAMPTZ,
 fondo_centimos INTEGER NOT NULL CHECK (fondo_centimos BETWEEN 0 AND 10000000),
 efectivo_ventas_centimos INTEGER CHECK (efectivo_ventas_centimos >= 0),
 contado_centimos INTEGER CHECK (contado_centimos BETWEEN 0 AND 10000000),
 esperado_centimos INTEGER CHECK (esperado_centimos >= 0),
 diferencia_centimos INTEGER,
 CONSTRAINT cierre_completo CHECK (
    (cerrada_en IS NULL AND efectivo_ventas_centimos IS NULL AND contado_centimos IS NULL AND esperado_centimos IS NULL AND diferencia_centimos IS NULL)
    OR (cerrada_en IS NOT NULL AND efectivo_ventas_centimos IS NOT NULL AND contado_centimos IS NOT NULL AND esperado_centimos IS NOT NULL AND diferencia_centimos IS NOT NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS caja_activa_por_usuario ON cajas(usuario_id) WHERE cerrada_en IS NULL;
CREATE INDEX IF NOT EXISTS cajas_usuario_fecha ON cajas(usuario_id, abierta_en DESC);
